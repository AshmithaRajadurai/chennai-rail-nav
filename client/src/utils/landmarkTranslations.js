/**
 * Returns localized name for a node in the requested language
 */
export function getNodeDisplayName(node, lang = 'en') {
  if (!node) return '';
  const translations = landmarkTranslations[node.nodeId];
  if (translations && translations[lang]) {
    return translations[lang];
  }
  if (lang === 'hi' && node.nameHi) {
    return node.nameHi;
  }
  if (lang === 'ta' && node.nameTa) {
    return node.nameTa;
  }
  return node.name || node.nodeId;
}

/**
 * Returns compact, non-overlapping label for SVG map badges
 */
export function getNodeShortLabel(node, lang = 'en') {
  if (!node) return '';
  const item = shortLandmarkLabels[node.nodeId];
  if (item && item[lang]) return item[lang];
  if (item && item.en) return item.en;
  return getNodeDisplayName(node, lang);
}

