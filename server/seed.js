// Helper to generate bidirectional edge pairs
function createBidirectionalEdge(
  stationId,
  from,
  to,
  distance,
  flags = {},
  instructionEn = '',
  reverseEn = '',
  instructionTa = '',
  reverseTa = ''
) {
  return [
    {
      stationId,
      fromNode: from,
      toNode: to,
      distance,
      hasStairs: flags.hasStairs || false,
      hasElevator: flags.hasElevator || false,
      hasRamp: flags.hasRamp || false,
      isOperational: flags.isOperational !== undefined ? flags.isOperational : true,
      instruction: instructionEn || `Walk ${distance}m towards ${to}`,
      instructionTa: instructionTa || `${distance} மீட்டர் தூரம் நடந்து செல்லவும்`,
    },
    {
      stationId,
      fromNode: to,
      toNode: from,
      distance,
      hasStairs: flags.hasStairs || false,
      hasElevator: flags.hasElevator || false,
      hasRamp: flags.hasRamp || false,
      isOperational: flags.isOperational !== undefined ? flags.isOperational : true,
      instruction: reverseEn || `Walk ${distance}m back towards ${from}`,
      instructionTa: reverseTa || `${distance} மீட்டர் தூரம் திரும்பி நடக்கவும்`,
    },
  ];
}

