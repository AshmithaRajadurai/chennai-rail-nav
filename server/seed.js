async function seedDatabase() {
  try {
    console.log('Connecting to MongoDB...');
    await mongoose.connect(process.env.MONGODB_URI);
    console.log('Connected to MongoDB successfully.');

    // Clear existing collections
    console.log('Clearing existing Station, Node, and Edge collections...');
    await Station.deleteMany({});
    await Node.deleteMany({});
    await Edge.deleteMany({});
    console.log('Existing collections cleared.');

    // Insert Stations
    console.log(`Inserting ${stationsData.length} stations...`);
    const insertedStations = await Station.insertMany(stationsData);
    console.log(`Inserted ${insertedStations.length} stations successfully.`);

    // Insert Nodes
    console.log(`Inserting ${nodesData.length} nodes...`);
    const insertedNodes = await Node.insertMany(nodesData);
    console.log(`Inserted ${insertedNodes.length} nodes successfully.`);

    // Insert Edges
    console.log(`Inserting ${edgesData.length} edges...`);
    const insertedEdges = await Edge.insertMany(edgesData);
    console.log(`Inserted ${insertedEdges.length} edges successfully.`);

    console.log('\n--- SEED SUMMARY ---');
    console.log(`Stations: ${insertedStations.length}`);
    console.log(`Nodes:    ${insertedNodes.length}`);
    console.log(`Edges:    ${insertedEdges.length}`);
    console.log('Ground truth Chennai RailNav database seeding completed successfully!');

    process.exit(0);
  } catch (error) {
    console.error('Error seeding database:', error);
    process.exit(1);
  }
}

seedDatabase();
